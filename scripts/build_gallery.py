def load_manifest(plots_dir: Path) -> list[dict[str, str]]:
    manifest_path = plots_dir / "manifest.json"
    if manifest_path.is_file():
        contents = json.loads(manifest_path.read_text(encoding="utf-8"))
        if isinstance(contents, list):
            return contents

    return [
        {
            "category": (
                relative.parent.as_posix() if relative.parent != Path(".") else "Uncategorized"
            ),
            "log": "",
            "plot": relative.as_posix(),
        }
        for relative in (
            item.relative_to(plots_dir) for item in sorted(plots_dir.rglob("*.png"))
        )
    ]


def collect_categories(plots_dirs: list[Path]) -> dict[str, dict[str, dict[str, Path]]]:
    categories: dict[str, dict[str, dict[str, Path]]] = defaultdict(lambda: defaultdict(dict))

    for plots_dir in plots_dirs:
        for item in load_manifest(plots_dir):
            plot_file = plots_dir / item["plot"]
            if plot_file.is_file():
                chart_key = item["log"] or item["plot"]
                categories[item["category"]][chart_key][plots_dir.name] = plot_file

    return categories


def render_ranking_sections(
    plot_files: list[Path],
    *,
    asset_root: Path,
    page_root: Path,
) -> list[str]:
    categories: dict[str, list[Path]] = defaultdict(list)

    for plot_file in plot_files:
        categories[plot_file.parent.name or "Rankings"].append(plot_file)

    sections: list[str] = []

    for category in sorted(categories):
        cards = []

        for plot_file in sorted(categories[category], key=lambda path: path.name):
            title = plot_file.stem.replace("_", " ")
            title_esc = html.escape(title)

            asset_path = asset_root / category / plot_file.name
            asset_path.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(plot_file, asset_path)

            relative_image = Path(os.path.relpath(asset_path, page_root)).as_posix()
            image_href = html.escape(relative_image)
            alt_text = html.escape(f"{title} ranking")
            caption_text = html.escape(f"{category} · {title} ranking")

            cards.append(
                "<article>"
                f"<h3>{title_esc}</h3>"
                '<div class="variants" style="grid-template-columns: minmax(0, 1fr);">'
                "<figure>"
                "<figcaption>"
                f'<span class="figure-label">{title_esc}</span>'
                f'<a class="figure-download" href="{image_href}" download>Download</a>'
                "</figcaption>"
                f'<button type="button" class="expand-button" '
                f'data-src="{image_href}" '
                f'data-alt="{alt_text}" '
                f'data-caption="{caption_text}" '
                f'aria-label="Expand chart {title_esc}">'
                f'<img class="chart-image" src="{image_href}" alt="{alt_text}" loading="lazy">'
                "</button>"
                "</figure>"
                "</div></article>"
            )

        sections.append(
            '<section class="category">'
            f'<h2>{html.escape(category)}</h2>'
            f'<div class="comparisons">{"".join(cards)}</div>'
            "</section>"
        )

    return sections


def render_sections(
    categories: dict[str, dict[str, dict[str, Path]]],
    column_names: list[str],
    *,
    asset_root: Path,
    page_root: Path,
    not_found_label: str = "Plot not found",
    label_suffix: str = "",
) -> list[str]:
    sections: list[str] = []

    for category in sorted(categories):
        cards = []

        for chart_key, variants in sorted(categories[category].items()):
            title = Path(chart_key).stem.replace("_", " ")
            title_esc = html.escape(title)
            columns = []

            for column_name in column_names:
                image_path = variants.get(column_name)

                if image_path is None:
                    columns.append(
                        f'<div class="missing"><strong>{html.escape(column_name)}</strong>'
                        f"<br>{html.escape(not_found_label)}</div>"
                    )
                    continue

                asset_path = asset_root / column_name / Path(chart_key).with_suffix(".png")
                asset_path.parent.mkdir(parents=True, exist_ok=True)
                shutil.copy2(image_path, asset_path)

                relative_image = Path(os.path.relpath(asset_path, page_root)).as_posix()

                image_href = html.escape(relative_image)
                column_esc = html.escape(column_name)
                alt_text = html.escape(f"{title}{label_suffix} from {column_name}")
                caption_text = html.escape(f"{column_name} · {title}{label_suffix}")

                columns.append(
                    "<figure>"
                    "<figcaption>"
                    f'<span class="figure-label">{column_esc}</span>'
                    f'<a class="figure-download" href="{image_href}" download>Download</a>'
                    "</figcaption>"
                    f'<button type="button" class="expand-button" '
                    f'data-src="{image_href}" '
                    f'data-alt="{alt_text}" '
                    f'data-caption="{caption_text}" '
                    f'aria-label="Expand chart {title_esc} from {column_esc}">'
                    f'<img class="chart-image" src="{image_href}" alt="{alt_text}" loading="lazy">'
                    "</button>"
                    "</figure>"
                )

            cards.append(
                "<article>"
                f"<h3>{title_esc}</h3>"
                f'<div class="variants" style="grid-template-columns: repeat({len(column_names)}, minmax(0, 1fr));">'
                f'{"".join(columns)}'
                "</div></article>"
            )

        sections.append(
            '<section class="category">'
            f'<h2>{html.escape(category)}</h2>'
            f'<div class="comparisons">{"".join(cards)}</div>'
            "</section>"
        )

    return sections



def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "plots_dirs",
        nargs="*",
        type=Path,
        default=[Path("plots")],
        help="One or more plot directories. Matching plots are displayed side by side.",
    )
    parser.add_argument("--output", type=Path, default=Path("site/index.html"))
    parser.add_argument(
        "--ranking-plots",
        nargs="*",
        type=Path,
        default=[],
        metavar="RANKING_PLOT",
        help="Paths to ranking PNG charts generated by an external ranking script. "
        "Each chart is displayed on the rankings/ subsite.",
    )
    args = parser.parse_args()

    plots_dirs = [plots_dir.resolve() for plots_dir in args.plots_dirs]
    output_path = args.output.resolve()

    missing_directories = [str(plots_dir) for plots_dir in plots_dirs if not plots_dir.is_dir()]
    if missing_directories:
        print(f"Plots directory does not exist: {', '.join(missing_directories)}", file=sys.stderr)
        return 2

    directory_names = [plots_dir.name for plots_dir in plots_dirs]
    if len(set(directory_names)) != len(directory_names):
        print("Plot directory names must be unique so they can label comparisons.", file=sys.stderr)
        return 2

    ranking_plot_files = [plot_file.resolve() for plot_file in args.ranking_plots]

    missing_plot_files = [str(plot_file) for plot_file in ranking_plot_files if not plot_file.is_file()]
    if missing_plot_files:
        print(f"Ranking plot does not exist: {', '.join(missing_plot_files)}", file=sys.stderr)
        return 2

    ranking_category_names = {plot_file.parent.name or "Rankings" for plot_file in ranking_plot_files}
    ranking_keys = [(plot_file.parent.name, plot_file.name) for plot_file in ranking_plot_files]
    if len(set(ranking_keys)) != len(ranking_keys):
        print(
            "Ranking plot directory and file names must be unique so they can label rankings.",
            file=sys.stderr,
        )
        return 2

    ranking_page_path = output_path.parent / RANKING_DIR_NAME / "index.html"

    categories = collect_categories(plots_dirs)
    sections = render_sections(
        categories,
        directory_names,
        asset_root=output_path.parent / "assets",
        page_root=output_path.parent,
    )

    ranking_sections = render_ranking_sections(
        ranking_plot_files,
        asset_root=ranking_page_path.parent / "assets",
        page_root=ranking_page_path.parent,
    )

    ranking_nav = RANKING_NAV if ranking_plot_files else ""
    output_path.parent.mkdir(parents=True, exist_ok=True)

    joined_sections = "".join(sections) or "<p>No PNG plots found.</p>"

    output_path.write_text(
        "<!doctype html>"
        '<html lang="en"><head><meta charset="utf-8">'
        '<meta name="viewport" content="width=device-width, initial-scale=1">'
        "<title>Benchmark plots</title>"
        f"<style>{PAGE_STYLE}{LIGHTBOX_STYLE}</style>"
        "</head><body><main>"
        "<h1>Benchmark plot comparison</h1>"
        f'<p class="subtitle">{sum(map(len, categories.values()))} matched plot(s) across '
        f"{len(categories)} categor{'y' if len(categories) == 1 else 'ies'} and "
        f"{len(plots_dirs)} plot director{'y' if len(plots_dirs) == 1 else 'ies'}.</p>"
        f"{ranking_nav}"
        f"{joined_sections}"
        f"{LIGHTBOX_HTML}<script>{LIGHTBOX_JS}</script>"
        "</main></body></html>\n",
        encoding="utf-8",
    )

    print(f"Created {output_path}")

    if ranking_plot_files:
        joined_ranking_sections = "".join(ranking_sections) or "<p>No ranking charts were generated.</p>"
        ranking_page_path.parent.mkdir(parents=True, exist_ok=True)
        ranking_page_path.write_text(
            "<!doctype html>"
            '<html lang="en"><head><meta charset="utf-8">'
            '<meta name="viewport" content="width=device-width, initial-scale=1">'
            "<title>Ranking charts</title>"
            f"<style>{PAGE_STYLE}{LIGHTBOX_STYLE}</style>"
            "</head><body><main>"
            "<h1>Ranking chart comparison</h1>"
            f"{RANKING_PAGE_NAV}"
            f'<p class="subtitle">{len(ranking_plot_files)} ranking chart(s) across '
            f"{len(ranking_category_names)} categor{'y' if len(ranking_category_names) == 1 else 'ies'}.</p>"
            f"{joined_ranking_sections}"
            f"{LIGHTBOX_HTML}<script>{LIGHTBOX_JS}</script>"
            "</main></body></html>\n",
            encoding="utf-8",
        )
        print(f"Created {ranking_page_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
